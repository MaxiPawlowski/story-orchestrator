import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../../..');
const TEMPLATE = 'test/scenarios/v29-04-c2-cue-on.json';
export const ARMS = { on: 'test/scenarios/v30-d2-offscreen-cue-on.json', off: 'test/scenarios/v30-d2-offscreen-cue-off.json' };
export const STORY_ID = 'so-v30-d2';
export const STORAGE_PREFIX = (arm) => `so-v30-d2${arm}-`;
const NARRATOR = '/sendas name="DM Narrator" ';

export const readFrozen = () => JSON.parse(readFileSync(join(HERE, 'frozen.json'), 'utf8'));
const readOld = () => JSON.parse(readFileSync(join(ROOT, 'test/measurements/v2.9/04-c2c5/frozen.json'), 'utf8'));

export function buildArm(arm) {
  const template = JSON.parse(readFileSync(join(ROOT, TEMPLATE), 'utf8'));
  const frozen = readFrozen();
  const old = new Map(readOld().opportunities.map((entry) => [entry.id, entry]));
  const screens = new Map(frozen.opportunities.map((entry) => [`${NARRATOR}${old.get(entry.id).event}`, `${NARRATOR}${entry.screen}`]));
  let replaced = 0;
  const steps = template.steps.map((step) => {
    if (step.ext_setting?.key?.join('.') === 'settings.characters.cues') return { ext_setting: { ...step.ext_setting, value: arm === 'on' } };
    if (step.import_story) {
      const story = step.import_story;
      return { import_story: {
        ...story, id: STORY_ID, title: 'SO-V30-D2 Off-screen cues',
        description: 'v3.0 D2 corpus: 30 reaction cues whose event is told only through the cue, plus 10 no-cue opportunities.',
        qualities: story.qualities.map((quality) => ({ ...quality, rubric: `Harness latch for opportunity ${quality.key.slice(3)}, set with /cp set.` })),
      } };
    }
    if (typeof step.slash === 'string' && screens.has(step.slash)) { replaced += 1; return { ...step, slash: screens.get(step.slash) }; }
    if (typeof step.eval === 'string') return { ...step, eval: step.eval.replaceAll('so-v29-c2on-', STORAGE_PREFIX(arm)) };
    return step;
  });
  if (replaced !== frozen.opportunities.length) throw new Error(`replaced ${replaced} narrator lines, expected ${frozen.opportunities.length}`);
  return {
    ...template,
    _note: `v3.0 D2 ${arm} arm (frozen 2026-10-30 before inference): the v2.9 04 C2 corpus with each event told only through its cue (the narrator line is neutral), characters.cues ${arm === 'on'}; replies tagged ${STORAGE_PREFIX(arm)}<id> in localStorage. Generated by test/measurements/v3.0/d2-offscreen/build.mjs; spec arms.json.`,
    steps,
  };
}

const render = (value) => `${JSON.stringify(value, null, 2)}\n`.replace(/\n/g, '\r\n');

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [arm, path] of Object.entries(ARMS)) {
    const text = render(buildArm(arm));
    if (check) {
      let current = '';
      try { current = readFileSync(join(ROOT, path), 'utf8'); } catch { current = ''; }
      if (current !== text) { stale += 1; console.error(`stale: ${path}`); }
    } else writeFileSync(join(ROOT, path), text);
  }
  if (stale) process.exit(1);
  console.log(check ? 'current' : `wrote ${Object.values(ARMS).join(', ')}`);
}
