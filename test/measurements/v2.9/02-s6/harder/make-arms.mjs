import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../../../", import.meta.url);
const here = new URL("./", import.meta.url);
const sha = (text) => createHash("sha256").update(text).digest("hex");
const GROUP = "Group: S6H Clerks";
const set = JSON.parse(readFileSync(new URL("cards.json", here), "utf8"));
const names = set.members.map((m) => m.card.name);
const story = {
  id: "so-v29-02-s6h",
  title: "SO-V29-02 S6H Packet Office",
  description: `v2.9 02 S6 harder corpus: three near-identical self-voiced members whose only systematic difference is their delivery sheet. ${set.setting}`,
  roster: [
    ...set.members.map((m) => ({ id: m.id, name: m.card.name, role: "a packet-office clerk", polish: m.sheet })),
    { id: "narrator", name: "DM Narrator", role: "narrator", view: "omniscient" },
  ],
  qualities: [{ key: "departed", type: "bool", source: "extractor", rubric: "Has the shift ended and everyone left the office?" }],
  checkpoints: [
    { id: "office", name: "Office", player_name: "The Packet Office", type: "anchor", start: true, objective: set.objective },
    { id: "after", name: "After", type: "anchor", objective: "The shift is over." },
  ],
  transitions: [{ from: "office", to: "after", priority: 1, gate: { q: "departed", op: "==", v: true } }],
  requirements: { members: [...names, "DM Narrator"] },
};
const quote = (text) => text.replace(/"/g, "'");
const arm = (name) => {
  const delivery = name === "prevention";
  const check = `for (const key of Object.keys(globalThis).filter((k) => k.startsWith('storyOrchestratorDebug'))) delete globalThis[key]; const s = globalThis.storyOrchestratorRuntime.getGlobalSettings(); if (s.image.enabled || s.sprites.enabled) throw new Error('media must be off'); if (s.characters.delivery !== ${delivery}) throw new Error('delivery setting is not the arm'); globalThis.storyOrchestratorDebugExtractionResponse = 'SCENE_NONE'; const ctx = SillyTavern.getContext(); for (let id = ctx.chat.length - 1; id >= 0; id -= 1) await ctx.deleteMessage(id, undefined, false); return { arm: '${name}', delivery: s.characters.delivery };`;
  const steps = [
    ...(delivery ? [] : [{ ext_setting: { extension: "story-orchestrator", key: ["settings", "characters", "delivery"], value: false } }]),
    { eval: check },
    { import_story: story },
    { eval: "globalThis.storyOrchestratorRuntime.setUiSettings({ authorView: false }); return true;" },
  ];
  set.situations.forEach((situation, index) => {
    const n = index + 1;
    steps.push({ slash: `/sendas name="DM Narrator" ${quote(situation)}` });
    const order = names.map((_, k) => names[(k + index) % names.length]);
    for (const member of order) {
      steps.push({ slash: `/trigger await=true "${member}"` });
      steps.push({ log: true, eval: `const ctx = SillyTavern.getContext(); const row = ctx.chat[ctx.chat.length - 1]; if (row?.name !== '${member}') throw new Error('last reply is not ${member}: ' + row?.name); localStorage.setItem('so-v29-s6h-${name}-' + String(${n}).padStart(2, '0') + '-${member}', JSON.stringify({ mes: row.mes ?? '', reasoningLen: (row.extra?.reasoning ?? '').length, at: Date.now() })); return { stored: ${n}, member: '${member}', length: (row.mes ?? '').length };` });
    }
  });
  return {
    _note: `v2.9 02 S6 harder arm ${name} (frozen 2026-10-25 before inference, generated by test/measurements/v2.9/02-s6/harder/make-arms.mjs from cards.json): 20 narrator situations x 3 near-identical self-voiced members (${names.join(", ")}) = 60 real Artemis replies, delivery ${delivery ? "on (the default)" : "off through characters.delivery"}; reply order rotates per situation; extraction pinned SCENE_NONE (not the measured path); thinking and inner voice on. Replies land in localStorage keys so-v29-s6h-${name}-*. Needs the cards and group from setup.js. Run on a model lane with --sandbox --group '${GROUP}'.`,
    requires: { lane: "model", group: GROUP, members: [...names, "DM Narrator"] },
    steps,
  };
};
const out = {};
for (const name of ["baseline", "prevention"]) {
  const text = `${JSON.stringify(arm(name), null, 2)}\n`;
  writeFileSync(new URL(`test/scenarios/v29-02-s6h-${name}.json`, root), text);
  out[name] = sha(text);
}
console.log(JSON.stringify(out));
