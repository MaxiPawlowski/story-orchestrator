#!/usr/bin/env node
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const SOURCE = "docs/authoring/story-guide.md";
export const OUT = "docs/guide/author";
const TOPICS_DIR = "topics";
const MARKER = /^<!-- topic: ([a-z0-9-]+) -->$/;

const banner = (from) => `<!-- Generated by scripts/docs/split-guide.mjs from ${SOURCE}${from ? ` (${from})` : ""}. Edit the source, then run npm run docs:guide. -->`;

const HAND_WRITTEN = [
  ["studio.md", "Checkpoint Studio", "the visual editor: tabs, diagnostics, saving to the library"],
  ["wizard.md", "The setup wizard", "from a premise to a playable story, and what it creates on your install"],
  ["macros-and-commands.md", "Macros and slash commands", "story values in your cards and prompts, and the author commands"],
  ["examples.md", "Examples", "a complete story to read, import and play"],
];

export function parseGuide(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const h2 = [];
  let current = null;
  for (const line of lines) {
    if (line.startsWith("## ")) {
      current = { title: line.slice(3).trim(), lines: [] };
      h2.push(current);
    } else if (current) current.lines.push(line);
  }
  const preface = lines.slice(1, lines.findIndex((line) => line.startsWith("## "))).join("\n").trim();
  const find = (prefix) => h2.find((part) => part.title.startsWith(prefix));
  const fields = find("Part 1");
  const topics = [];
  let topic = null;
  for (let i = 0; i < fields.lines.length; i += 1) {
    const line = fields.lines[i];
    if (line.startsWith("### ")) {
      const marker = MARKER.exec(fields.lines[i + 1] ?? "");
      if (!marker) throw new Error(`${SOURCE}: "${line}" has no topic marker under it`);
      topic = { id: marker[1], title: line.slice(4).trim(), lines: [] };
      topics.push(topic);
      i += 1;
    } else if (topic) topic.lines.push(line);
  }
  const body = (part) => part.lines.join("\n").trim();
  return {
    title: lines[0].replace(/^# /, "").trim(),
    preface,
    plays: { title: find("How a story plays").title, text: body(find("How a story plays")) },
    practices: { title: find("Part 2").title, text: body(find("Part 2")) },
    steps: { title: find("Part 3").title, text: body(find("Part 3")) },
    topics: topics.map((item) => ({ ...item, text: item.lines.join("\n").trim() })),
  };
}

const page = (from, title, text, nav) => [banner(from), "", `# ${title}`, "", text, "", nav, ""].join("\n");

export function renderPages(text) {
  const guide = parseGuide(text);
  const pages = new Map();
  const index = "[Author's guide](README.md)";
  pages.set("how-a-story-plays.md", page("How a story plays", guide.plays.title, guide.plays.text, `---\n\n${index} · next: [${guide.topics[0].title}](${TOPICS_DIR}/${guide.topics[0].id}.md)`));
  guide.topics.forEach((topic, i) => {
    const prev = guide.topics[i - 1];
    const next = guide.topics[i + 1];
    const nav = [
      `[Author's guide](../README.md)`,
      prev ? `previous: [${prev.title}](${prev.id}.md)` : `previous: [How a story plays](../how-a-story-plays.md)`,
      next ? `next: [${next.title}](${next.id}.md)` : `next: [Good practices and traps](../good-practices.md)`,
    ].join(" · ");
    pages.set(`${TOPICS_DIR}/${topic.id}.md`, page(`topic: ${topic.id}`, topic.title, `Guide topic \`${topic.id}\` (the Studio's "How to write this" and the wizard's \`readGuide\` show the same topic).\n\n${topic.text}`, `---\n\n${nav}`));
  });
  pages.set("good-practices.md", page("Part 2", "Good practices and traps", guide.practices.text, `---\n\n${index} · next: [Build a story step by step](step-by-step.md)`));
  pages.set("step-by-step.md", page("Part 3", "Build a story step by step", guide.steps.text, `---\n\n${index}`));
  const readme = [
    banner(),
    "",
    `# ${guide.title}`,
    "",
    guide.preface,
    "",
    "## Start here",
    "",
    "- [How a story plays](how-a-story-plays.md): the two rules most advice comes from.",
    "- [Build a story step by step](step-by-step.md): the wizard's four steps, done by hand or with the wizard.",
    "- [Good practices and traps](good-practices.md): what live play taught, one line each.",
    "",
    "## Tools",
    "",
    ...HAND_WRITTEN.map(([file, title, line]) => `- [${title}](${file}): ${line}.`),
    "",
    `## The fields, one page per topic (${guide.topics.length})`,
    "",
    ...guide.topics.map((topic) => `- [${topic.title}](${TOPICS_DIR}/${topic.id}.md) (\`${topic.id}\`)`),
    "",
  ].join("\n");
  pages.set("README.md", readme);
  return pages;
}

const generatedFiles = (out) => {
  const found = [];
  const walk = (dir, prefix) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walk(join(dir, entry.name), rel);
      else if (entry.name.endsWith(".md") && readFileSync(join(dir, entry.name), "utf8").startsWith("<!-- Generated by scripts/docs/split-guide.mjs")) found.push(rel);
    }
  };
  walk(out, "");
  return found.sort();
};

export function staleIssues(root = ROOT) {
  const pages = renderPages(readFileSync(join(root, SOURCE), "utf8"));
  const out = join(root, OUT);
  const issues = [];
  for (const [rel, text] of pages) {
    const path = join(out, rel);
    if (!existsSync(path)) issues.push(`${OUT}/${rel} is missing`);
    else if (readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text) issues.push(`${OUT}/${rel} is stale`);
  }
  for (const rel of generatedFiles(out)) if (!pages.has(rel)) issues.push(`${OUT}/${rel} is generated but no longer in the guide`);
  return issues;
}

export function writePages(root = ROOT) {
  const pages = renderPages(readFileSync(join(root, SOURCE), "utf8"));
  const out = join(root, OUT);
  for (const rel of generatedFiles(out)) if (!pages.has(rel)) rmSync(join(out, rel));
  for (const [rel, text] of pages) {
    mkdirSync(dirname(join(out, rel)), { recursive: true });
    writeFileSync(join(out, rel), text);
  }
  return [...pages.keys()];
}

const invoked = process.argv[1] ? resolve(process.argv[1]) : "";
if (fileURLToPath(import.meta.url) === invoked) {
  if (process.argv.includes("--check")) {
    const issues = staleIssues();
    issues.forEach((issue) => console.error(issue));
    process.exitCode = issues.length ? 1 : 0;
    if (!issues.length) console.log(`${OUT} matches ${SOURCE}`);
  } else console.log(`wrote ${writePages().length} pages to ${OUT}`);
}
