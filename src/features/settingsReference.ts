export const renderSettingsReference = (): string => {
  const rows = settingRows();
  const sections = FEATURE_AREAS.flatMap((area) => {
    const inArea = rows.filter((row) => row.area === area);
    if (!inArea.length) return [];
    const copy = SETTINGS_AREA_COPY[area];
    return [
      `## ${copy.label}`,
      "",
      `${copy.oneLine} ${moreLink(copy.doc)}`,
      "",
      "| Setting | Where | Scope | What it does | Default | Key |",
      "|---|---|---|---|---|---|",
      ...inArea.map((row) => `| **${cell(row.label)}** | ${cell(row.where)} | ${row.scope} | ${cell(row.help)} | ${cell(row.defaultText)} | \`${row.key}\` |`),
      "",
    ];
  });
  return [
    REFERENCE_BANNER,
    "# Settings reference",
    "",
    "Every setting, by area. Each row says where the control is, which scopes it has, what it does and costs, and its effective default: what",
    "an untouched install does. Rarely changed settings sit under their section's **Advanced** fold. What each part costs in model calls and",
    "waiting: [Costs and waiting](README.md#costs-and-waiting).",
    "",
    ...SCOPE_INTRO,
    ...sections,
    ...experimentsSection(),
    "---",
    "",
    "[Setup](README.md)",
    "",
  ].join("\n");
};

const percent = (value: number) => `${Math.round(value * 100)}%`;

export const judgeMeasurement = (use: JudgeUseKey): string => {
  if (JUDGE_USE_COPY[use].sends.startsWith("nothing:")) return "No judge call: counted in code";
  const fact = JUDGE_READINESS[use];
  if (fact.calibration === null) return (WARDEN_RIDERS as readonly string[]).includes(use) ? "Not measured; rides the warden's call" : "Not measured";
  if (fact.passed === false) return `Below its floor (${percent(fact.calibration)}); on all the same`;
  return `Measured: ${percent(fact.calibration)}, about ${String(fact.latencyP50Ms)} ms`;
};

export const localJudgeMeasurement = (use: JudgeUseKey): string => {
  const fact = ROUTED_READINESS["systemone-local"]?.[use];
  return fact?.passed && fact.calibration !== null ? `Measured: ${percent(fact.calibration)}` : "Not measured: refused there";
};

const needsOf = (use: JudgeUseKey): string => {
  const dependency = JUDGE_USE_DEPENDENCIES[use];
  if (dependency) return JUDGE_USE_COPY[dependency].label;
  if ((WARDEN_RIDERS as readonly string[]).includes(use)) return "Continuity warden";
  return "";
};

