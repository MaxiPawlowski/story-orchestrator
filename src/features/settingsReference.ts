const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const productDefaults = (): Record<string, unknown> => {
  const defaults = defaultGlobalSettings();
  return { ...defaults, memory: { ...defaults.memory, chapters: DEFAULT_CHAPTER_SETTINGS } };
};

const valueAt = (source: unknown, key: string): unknown => key.split(".").reduce<unknown>((node, part) => (isRecord(node) ? node[part] : undefined), source);

export const formatDefault = (key: string, value: unknown): string => {
  if (key.includes("*")) return "Per entry";
  if (value === undefined) return ABSENT_DEFAULTS[key] ?? "Not set";
  if (value === null || value === "") return "Not set";
  if (typeof value === "boolean") return value ? "On" : "Off";
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return `\`${value}\``;
  if (Array.isArray(value)) return value.length ? value.map((item) => `\`${String(item)}\``).join(", ") : "None";
  return "Per entry";
};

const GROUP_OWNERS: Record<string, string> = { "judge.uses": "judge", "judge.provider": "judge" };

export const ownerOf = (key: string): Feature | null => {
  const prefix = key.split(".*")[0];
  const grouped = GROUP_OWNERS[prefix];
  if (grouped) return FEATURES.find((feature) => feature.id === grouped) ?? null;
  return FEATURES.find((feature) => feature.settings.some((owned) => coversSetting(owned, prefix) || coversSetting(prefix, owned))) ?? null;
};

export const featureControlFor = (key: string): StoryFeatureId | null =>
  STORY_FEATURE_IDS.find((id) => FEATURE_CONTROLS[id].controls.some((control) => control.path === key)) ?? null;

const isDeviceSetting = (key: string) => (DEVICE_SETTING_PATHS as readonly string[]).includes(key);

const trail = (...parts: string[]) => parts.filter(Boolean).join(" → ");

const DEVICE_LOCATION = "the This device chip on the same row";

const LOCATION_OVERRIDES: Record<string, string> = {
  "sprites.renderPreset": trail("Studio", "Sprite builder"),
};

const ownerLocation = (owner: Feature | null): string => {
  if (!owner) return CONTEXT_LABELS.orchestrator;
  const intent = owner.where.workspace;
  if (intent?.context === "story" && intent.page === "features" && intent.feature) {
    return trail(CONTEXT_LABELS.orchestrator, featuresPageLabel, FEATURE_CONTROLS[intent.feature].name);
  }
  return trail(...owner.where.label.split(" › ").filter((part) => part !== "Overview"));
};

const featureLocation = (feature: StoryFeatureId): string => {
  const name = FEATURE_CONTROLS[feature].name;
  const home = FEATURE_INSTALL_HOMES[feature];
  const install = home ? trail(CONTEXT_LABELS.orchestrator, pageLabel("orchestrator", home.page)) : trail(CONTEXT_LABELS.orchestrator, featuresPageLabel, name);
  return `${install}; this chat: ${trail(CONTEXT_LABELS.story, pageLabel("story", "features"), name)}`;
};

export const locationOf = (key: string, owner: Feature | null): string => {
  const feature = featureControlFor(key);
  const base = LOCATION_OVERRIDES[key] ?? (feature ? featureLocation(feature) : ownerLocation(owner));
  return isDeviceSetting(key) ? `${base}; this device: ${DEVICE_LOCATION}` : base;
};

export const scopeOf = (key: string): string => {
  const scopes = [featureControlFor(key) ? "Install, story, chat" : "Install"];
  if (isDeviceSetting(key)) scopes.push("device");
  return scopes.join(", ");
};

export interface SettingRow {
  key: string;
  area: FeatureArea;
  label: string;
  where: string;
  scope: string;
  help: string;
  defaultText: string;
}

export const settingRows = (): SettingRow[] => {
  const defaults = productDefaults();
  return Object.entries(SETTING_COPY).map(([key, copy]) => {
    const owner = ownerOf(key);
    return {
      key, area: owner?.area ?? "setup", label: copy.label, where: locationOf(key, owner), scope: scopeOf(key), help: copy.help,
      defaultText: EFFECTIVE_DEFAULTS[key] ?? formatDefault(key, valueAt(defaults, key)),
    };
  });
};

